function [lhs, rhs] = static_resid(y, x, params)
T = NaN(9, 1);
lhs = NaN(10, 1);
rhs = NaN(10, 1);
T(1) = params(6)*y(3)^params(5);
T(2) = y(4)^params(4);
T(3) = y(3)^(1-params(1));
T(4) = y(2)^params(1);
T(5) = params(1)*y(2)^(params(1)-1);
T(6) = y(3)^(-params(1));
T(7) = (y(6)/(1-params(1)))^(1-params(1));
T(8) = 1/y(10)*T(7);
T(9) = (y(7)/params(1))^params(1);
lhs(1) = 1-params(2)*(1+y(7)-params(3));
rhs(1) = 0;
lhs(2) = y(2)-y(2)*(1-params(3))-y(5);
rhs(2) = 0;
lhs(3) = T(1)*T(2)-y(6);
rhs(3) = 0;
lhs(4) = y(1)-T(3)*y(10)*T(4);
rhs(4) = 0;
lhs(5) = y(7);
rhs(5) = T(3)*T(5);
lhs(6) = y(6);
rhs(6) = T(6)*(1-params(1))*T(4);
lhs(7) = y(1)-y(4)-y(5);
rhs(7) = 0;
lhs(8) = y(8);
rhs(8) = y(1)-y(7)*y(2)-y(3)*y(6);
lhs(9) = y(9);
rhs(9) = T(8)*T(9);
lhs(10) = y(10);
rhs(10) = y(10)^params(7)*exp(x(1));
end
